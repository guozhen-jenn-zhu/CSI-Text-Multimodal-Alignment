def get_all_templates(dataset: str) -> List[Dict[str, Any]]:
    """Retrieve all template entries for a given dataset as a flat list."""
    if dataset == "csibench":
        entries = []
        for task_templates in CSIBENCH_TEMPLATES.values():
            entries.extend(task_templates)
        return entries
    elif dataset == "xrf55":
        entries = []
        for group_templates in XRF55_TEMPLATES.values():
            entries.extend(group_templates)
        return entries
    elif dataset == "signfi":
        return SIGNFI_TEMPLATES
    else:
        raise ValueError(f"Unknown dataset: {dataset}. Choose from: csibench, xrf55, signfi")


def get_task_templates(dataset: str, task: str) -> List[Dict[str, Any]]:
    """Retrieve templates for a specific task within a dataset."""
    if dataset == "csibench":
        if task not in CSIBENCH_TEMPLATES:
            raise ValueError(f"Unknown CSI-Bench task: {task}. Available: {list(CSIBENCH_TEMPLATES.keys())}")
        return CSIBENCH_TEMPLATES[task]
    elif dataset == "xrf55":
        if task not in XRF55_TEMPLATES:
            raise ValueError(f"Unknown XRF55 group: {task}. Available: {list(XRF55_TEMPLATES.keys())}")
        return XRF55_TEMPLATES[task]
    elif dataset == "signfi":
        return SIGNFI_TEMPLATES
    else:
        raise ValueError(f"Unknown dataset: {dataset}")


def generate_composite_caption(
    user_id: str,
    activity: str,
    proximity: str,
    template_idx: int = 0,
) -> str:
    """Generate a single Level 2 composite caption from attribute values."""
    user_desc = _USER_DESCRIPTIONS[user_id]
    act_desc = _ACTIVITY_DESCRIPTIONS[activity]
    dist_desc = _PROXIMITY_DESCRIPTIONS[proximity]
    pattern = CSIBENCH_COMPOSITE_TEMPLATES["template_patterns"][template_idx]
    return pattern.format(user_desc=user_desc, activity=act_desc, distance=dist_desc)
